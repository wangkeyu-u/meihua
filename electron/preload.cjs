const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('zhuge', {
  initialize: () => ipcRenderer.invoke('initialize'),
  saveAgentConfig: (draft) => ipcRenderer.invoke('save-agent-config', draft),
  runWorkflow: (id, prompt, files, agentId) => ipcRenderer.invoke('run-workflow', id, prompt, files, agentId),
  answerInputRequest: (id, action, values) => ipcRenderer.invoke('answer-input-request', id, action, values),
  runtimeSettings: () => ipcRenderer.invoke('runtime-settings'),
  saveVerificationConfig: (workspace, draft) => ipcRenderer.invoke('save-verification-config', workspace, draft),
  saveBackupPolicy: (retainDays) => ipcRenderer.invoke('save-backup-policy', retainDays),
  previewBackupCleanup: () => ipcRenderer.invoke('preview-backup-cleanup'),
  applyBackupCleanup: (id) => ipcRenderer.invoke('apply-backup-cleanup', id),
  openRuntimeFolder: () => ipcRenderer.invoke('open-runtime-folder'),
  listTasks: (sessionId) => ipcRenderer.invoke('list-tasks', sessionId),
  getTask: (id) => ipcRenderer.invoke('get-task', id),
  pauseTask: (id) => ipcRenderer.invoke('pause-task', id),
  resumeTask: (id) => ipcRenderer.invoke('resume-task', id),
  cancelTask: (id) => ipcRenderer.invoke('cancel-task', id),
  taskCheckpoints: (id) => ipcRenderer.invoke('task-checkpoints', id),
  checkpointDiff: (id, checkpointId) => ipcRenderer.invoke('checkpoint-diff', id, checkpointId),
  undoTask: (id) => ipcRenderer.invoke('undo-task', id),
  restoreTask: (id) => ipcRenderer.invoke('restore-task', id),
  exportTaskDiagnostics: (id) => ipcRenderer.invoke('export-task-diagnostics', id),
  listExperiences: () => ipcRenderer.invoke('list-experiences'),
  decideExperience: (id, status) => ipcRenderer.invoke('decide-experience', id, status),
  listMemories: () => ipcRenderer.invoke('list-memories'),
  saveMemory: (draft) => ipcRenderer.invoke('save-memory', draft),
  deleteMemory: (id) => ipcRenderer.invoke('delete-memory', id),
  listMcpServices: () => ipcRenderer.invoke('list-mcp-services'),
  searchMcpRegistry: (query) => ipcRenderer.invoke('search-mcp-registry', query),
  prepareMcpRegistry: (name, version, optionId) => ipcRenderer.invoke('prepare-mcp-registry', name, version, optionId),
  addMcpRegistry: (name, version, optionId, values) => ipcRenderer.invoke('add-mcp-registry', name, version, optionId, values),
  saveMcpService: (draft) => ipcRenderer.invoke('save-mcp-service', draft),
  deleteMcpService: (name) => ipcRenderer.invoke('delete-mcp-service', name),
  loginMcpService: (name) => ipcRenderer.invoke('login-mcp-service', name),
  logoutMcpService: (name) => ipcRenderer.invoke('logout-mcp-service', name),
  testMcpService: (name) => ipcRenderer.invoke('test-mcp-service', name),
  selectWorkspace: () => ipcRenderer.invoke('select-workspace'),
  createDefaultWorkspace: () => ipcRenderer.invoke('create-default-workspace'),
  saveSettings: (settings) => ipcRenderer.invoke('save-settings', settings),
  updateSession: (id, patch) => ipcRenderer.invoke('update-session', id, patch),
  forkSession: (id) => ipcRenderer.invoke('fork-session', id),
  exportSession: (id) => ipcRenderer.invoke('export-session', id),
  switchWorkspace: (workspace) => ipcRenderer.invoke('switch-workspace', workspace),
  pickAttachments: () => ipcRenderer.invoke('pick-attachments'),
  listWorkspaceFiles: (path) => ipcRenderer.invoke('list-workspace-files', path),
  previewFile: (path) => ipcRenderer.invoke('preview-file', path),
  workspaceDiff: () => ipcRenderer.invoke('workspace-diff'),
  copyText: (text) => ipcRenderer.invoke('copy-text', text),
  createSession: () => ipcRenderer.invoke('create-session'),
  loadSession: (id) => ipcRenderer.invoke('load-session', id),
  reviewPrompt: (id, prompt, agentId, attachments) => ipcRenderer.invoke('review-prompt', id, prompt, agentId, attachments),
  listSkills: () => ipcRenderer.invoke('list-skills'),
  importSkillZip: () => ipcRenderer.invoke('import-skill-zip'),
  saveAgent: (draft) => ipcRenderer.invoke('save-agent', draft),
  deleteAgent: (id) => ipcRenderer.invoke('delete-agent', id),
  saveShortcut: (draft) => ipcRenderer.invoke('save-shortcut', draft),
  deleteShortcut: (id) => ipcRenderer.invoke('delete-shortcut', id),
  openShortcut: (id) => ipcRenderer.invoke('open-shortcut', id),
  reviseReview: (id, reviewId) => ipcRenderer.invoke('revise-review', id, reviewId),
  completeReview: (id, reviewId) => ipcRenderer.invoke('complete-review', id, reviewId),
  sendReviewedPrompt: (id, reviewId, choice) => ipcRenderer.invoke('send-reviewed-prompt', id, reviewId, choice),
  runDirectPrompt: (id, prompt, mode, agentId, attachments) => ipcRenderer.invoke('run-direct-prompt', id, prompt, mode, agentId, attachments),
  executePlan: (id) => ipcRenderer.invoke('execute-plan', id),
  dismissPlan: (id) => ipcRenderer.invoke('dismiss-plan', id),
  steerPrompt: (id, prompt, expectedTaskId, nodeId) => ipcRenderer.invoke('steer-prompt', id, prompt, expectedTaskId, nodeId),
  stop: (id) => ipcRenderer.invoke('stop-agent', id),
  answerApproval: (id, approved) => ipcRenderer.invoke('answer-approval', id, approved),
  onEvent: (listener) => {
    const handler = (_event, payload) => listener(payload);
    ipcRenderer.on('agent-event', handler);
    return () => ipcRenderer.removeListener('agent-event', handler);
  },
});
